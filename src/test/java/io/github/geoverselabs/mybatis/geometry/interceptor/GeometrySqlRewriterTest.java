    @Test
    void resultsAreCachedPerSqlText() {
        TestStrategies.Wrapping strategy = TestStrategies.mysqlHex();
        GeometrySqlRewriter rewriter = new GeometrySqlRewriter(strategy);
        String first = rewriter.rewrite("SELECT id,location FROM shop WHERE id=?", SHOP, true);
        String second = rewriter.rewrite(new String("SELECT id,location FROM shop WHERE id=?"), SHOP, true);
        assertThat(second).isSameAs(first).isEqualTo("SELECT id,HEX(location) AS location FROM shop WHERE id=?");
        assertThat(strategy.wrapCalls).hasValue(1);
        assertThat(rewriter.cacheSize()).isEqualTo(1);

        // different metadata or table matching mode are different entries
        rewriter.rewrite("SELECT id,location FROM shop WHERE id=?", SHOP, false);
        rewriter.rewrite("SELECT id,location FROM shop WHERE id=?",
            new GeometryColumns("shop", List.of("location"), null), true);
        assertThat(rewriter.cacheSize()).isEqualTo(3);

        rewriter.clearCache();
        assertThat(rewriter.cacheSize()).isZero();
    }

