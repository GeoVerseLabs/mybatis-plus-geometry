    @Test
    void pathologicalInputIsLinear() {
        // the former regex needed 762 ms for 1000 spaces and did not finish for 4000
        GeometrySqlRewriter rewriter = new GeometrySqlRewriter(new MySQLGeometryStrategy());
        long start = System.nanoTime();
        String spaces = "SELECT" + " ".repeat(100_000) + "location";
        assertThat(rewriter.rewrite(spaces, SHOP, false)).isSameAs(spaces);
        StringBuilder items = new StringBuilder("SELECT ST_Collect(ARRAY[");
        for (int i = 0; i < 5000; i++) {
            items.append(i == 0 ? "" : ",").append("ST_Point(?, ?)");
        }
        String noFrom = items.append("]) AS location").toString();
        assertThat(rewriter.rewrite(noFrom, SHOP, false)).isSameAs(noFrom);
        assertThat(System.nanoTime() - start).isLessThan(2_000_000_000L);
    }

