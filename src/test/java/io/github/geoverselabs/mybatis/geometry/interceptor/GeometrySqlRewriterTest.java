    @Test
    void postgresQuotingRules() {
        GeometryColumns columns = new GeometryColumns("public.\"Shop\"", List.of("\"Geom\""), List.of("id", "\"Geom\""));
        GeometrySqlRewriter rewriter = new GeometrySqlRewriter(TestStrategies.postgisEwkb());
        assertThat(rewriter.rewrite("SELECT id,\"Geom\" FROM public.\"Shop\" WHERE id=?", columns, true))
            .isEqualTo("SELECT id,encode(ST_AsEWKB(\"Geom\"), 'hex') AS \"Geom\" FROM public.\"Shop\" WHERE id=?");
        assertThat(rewriter.rewrite("SELECT * FROM \"Shop\" AS \"S\"", columns, true))
            .isEqualTo("SELECT \"S\".id, encode(ST_AsEWKB(\"S\".\"Geom\"), 'hex') AS \"Geom\" FROM \"Shop\" AS \"S\"");
        // dollar quotes and escape strings hide commas, quotes and keywords
        assertThat(rewriter.rewrite(
            "SELECT $$\"Geom\", x$$ AS s, E'it\\'s, from' AS e, \"Geom\" FROM \"Shop\"", columns, true))
            .isEqualTo("SELECT $$\"Geom\", x$$ AS s, E'it\\'s, from' AS e, "
                + "encode(ST_AsEWKB(\"Geom\"), 'hex') AS \"Geom\" FROM \"Shop\"");
    }

