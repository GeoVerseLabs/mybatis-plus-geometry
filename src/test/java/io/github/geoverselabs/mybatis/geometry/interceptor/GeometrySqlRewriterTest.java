    @Test
    void wrapExpressionStripsOnlyATrailingAlias() {
        assertThat(wrap(column -> "ST_AsBinary(" + column + ")")).isEqualTo("ST_AsBinary(x)");
        assertThat(wrap(column -> "CONCAT('a AS b', " + column + ") as \"y\"")).isEqualTo("CONCAT('a AS b', x)");
        assertThat(wrap(column -> "(" + column + " || ' AS x')")).isEqualTo("(x || ' AS x')");
        assertThat(wrap(column -> "  HEX(" + column + ")  AS  x  ")).isEqualTo("HEX(x)");
        assertThat(wrap(column -> "CAST(" + column + " AS text)")).isEqualTo("CAST(x AS text)");
        assertThat(wrap(column -> "HEX(" + column + ") AS 'x'")).isEqualTo("HEX(x)");
        assertThat(wrap(column -> "'unterminated")).isEqualTo("'unterminated");
        assertThatThrownBy(() -> wrap(column -> null)).isInstanceOf(IllegalStateException.class)
            .hasMessageContaining("wrapColumnForSelect");
        assertThatThrownBy(() -> wrap(column -> "  ")).isInstanceOf(IllegalStateException.class);
    }

    private static String wrap(java.util.function.UnaryOperator<String> wrapping) {
        return GeometrySqlRewriter.wrapExpression(
            new TestStrategies.Wrapping(DatabaseType.MYSQL, wrapping), "x", SqlDialect.MYSQL);
    }

