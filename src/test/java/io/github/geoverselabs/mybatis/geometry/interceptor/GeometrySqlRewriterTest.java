    @Test
    void dollarSignsInColumnNames() {
        GeometryColumns columns = new GeometryColumns("t", List.of("geo$loc"), List.of("id", "geo$loc"));
        GeometrySqlRewriter rewriter = new GeometrySqlRewriter(new MySQLGeometryStrategy());
        assertThat(rewriter.rewrite("SELECT * FROM t", columns, true))
            .isEqualTo("SELECT id, HEX(geo$loc) AS geo$loc FROM t");
        assertThat(rewriter.rewrite("SELECT id, geo$loc FROM t WHERE x = '$1'", columns, true))
            .isEqualTo("SELECT id, HEX(geo$loc) AS geo$loc FROM t WHERE x = '$1'");
    }

    @Test
    void columnNamesAreComparedWithoutQuotes() {
        GeometryColumns quoted = new GeometryColumns("`spot`", List.of("`point`"), List.of("id", "`point`"));
        GeometrySqlRewriter rewriter = new GeometrySqlRewriter(new MySQLGeometryStrategy());
        assertThat(rewriter.rewrite("SELECT id,`point` FROM `spot` WHERE id=?", quoted, true))
            .isEqualTo("SELECT id,HEX(`point`) AS `point` FROM `spot` WHERE id=?");
        assertThat(rewriter.rewrite("SELECT id, point FROM spot", quoted, true))
            .isEqualTo("SELECT id, HEX(point) AS point FROM spot");
        assertThat(rewriter.rewrite("SELECT * FROM spot", quoted, true))
            .isEqualTo("SELECT id, HEX(`point`) AS `point` FROM spot");
    }

